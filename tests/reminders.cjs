const assert=require('node:assert/strict');
const {NexoReminders}=require('../docs/reminder-core.js');
const base={id:'c1',status:'Nuevo',due:'2026-11-25'};
const before=Date.parse('2026-11-25T08:59:00-06:00');
const after=Date.parse('2026-11-25T09:00:00-06:00');
assert.equal(NexoReminders.pending([base],before).length,0,'Delivery must not fire before 9 AM in El Salvador');
assert.equal(NexoReminders.pending([base],after).length,1,'Delivery fires at its scheduled time');
assert.equal(NexoReminders.pending([{...base,status:'Finalizado'}],after).length,0,'Closed cases suppress every reminder');
const deliveryId='delivery:'+base.due;
assert.equal(NexoReminders.pending([{...base,deliveryReminders:{[deliveryId]:{dismissed:true}}}],after).length,0,'Acknowledged delivery stays dismissed across reload');
const snoozed={...base,deliveryReminders:{[deliveryId]:{snoozedUntil:'2026-11-25T09:15:00-06:00'}}};
assert.equal(NexoReminders.pending([snoozed],after).length,0,'Snooze suppresses immediate alert');
assert.equal(NexoReminders.pending([snoozed],after+15*60000).length,1,'Snooze fires after 15 minutes');
assert.equal(NexoReminders.pending([{...base,due:'2026-11-26',deliveryReminders:{[deliveryId]:{dismissed:true}}}],after+86400000).length,1,'Changing a deadline creates a new reminder');
const custom={id:'r1',title:'Follow up',at:'2026-11-25T08:00:00-06:00'};
assert.equal(NexoReminders.pending([{...base,due:'',reminders:[custom]}],after).length,1,'Personal reminders work without a delivery date');
assert.equal(NexoReminders.pending([{...base,due:'',reminders:[{...custom,dismissed:true}]}],after).length,0,'Acknowledged custom reminders stay dismissed');
assert.equal(NexoReminders.pending([{...base,due:'',reminders:[{...custom,at:'invalid'}]}],after).length,0,'Invalid dates do not trigger alerts');
const sounded=NexoReminders.pending([{...base,reminders:[],deliveryReminders:{[deliveryId]:{lastAlertAt:'2026-11-25T15:00:00Z'}}}],after);
assert.equal(sounded[0].lastAlertAt,'2026-11-25T15:00:00Z','A shown reminder preserves its sound acknowledgement');
assert.equal(NexoReminders.pending([{...base,status:'Finalizado',reminders:[custom]}],after).length,0);
console.log('11 reminder checks passed.');
